-- porte l'idée qu'il y a un gagnant, et la doctrine OXV interdit tout classement
-- entre pilotes. Le schéma décrit une intention que le produit refuse.
--
-- La laisser vide n'est pas neutre : elle rouvrira la question à chaque
-- relecture du schéma, et un jour quelqu'un la remplira.
