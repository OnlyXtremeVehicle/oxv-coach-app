--     `supabase/functions/`.
--   · **Le piège de nom est levé** : `duelService.ts` porte le mot mais lit
--     `app_session_analyses` sous RLS d'amitié. Il ne touche pas cette table et
--     survivra à sa suppression. Ne pas le renommer dans la même passe — un
--     renommage et une suppression dans un même lot rendent la relecture
--     illisible.
--
-- ----------------------------------------------------------------------------
-- CE QUI REMPLACE LE BESOIN, ET QUI EXISTE DÉJÀ
-- ----------------------------------------------------------------------------
--
-- Le plan tranche aussi la suite : *« Aucune table de comparaison n'est créée —
-- elle est éphémère, sans trace. L'amitié EST le consentement : `are_friends()`
-- exige déjà `accepted` des deux côtés. »*
--
-- La comparaison entre amis ne laisse donc rien derrière elle. C'est le
-- contraire d'un duel : on regarde ensemble, on ne conserve pas de verdict.
--
-- ----------------------------------------------------------------------------

begin;

-- `cascade` retire aussi les policies, index et contraintes portés par la
-- table. Aucune autre table ne la référence — vérifié : aucune clé étrangère
-- entrante.
drop table if exists public.duels cascade;

commit;
